const { createRequire } = require('node:module')
const path = require('node:path')
const { chromium } = createRequire('C:/Users/KIIT0001/Downloads/AD_JEET/.superpowers/worktrees/era-build/adjeet-site/package.json')('playwright')
;(async () => {
  const browser = await chromium.launch({ headless: true })
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, reducedMotion: 'no-preference' })
  await page.addInitScript(() => localStorage.setItem('adjeet-consent', 'declined'))
  await page.goto('http://127.0.0.1:4180/services', { waitUntil: 'domcontentloaded' })
  await page.evaluate(() => document.fonts.ready)
  await page.waitForFunction(() => document.querySelector('h1').hasAttribute('aria-label') && [...document.querySelectorAll('h1 *')].every(el => Number(getComputedStyle(el).opacity) > 0.99))
  await page.screenshot({ path: path.join(__dirname, 'desktop-services.png') })
  await page.locator('#storefront').evaluate(el => window.scrollTo({ top: scrollY + el.getBoundingClientRect().top - 130, behavior: 'instant' }))
  await page.waitForFunction(() => [...document.querySelectorAll('#storefront [data-reveal-text] *')].every(el => Number(getComputedStyle(el).opacity) > 0.99))
  await page.screenshot({ path: path.join(__dirname, 'desktop-service-list.png') })
  await browser.close()
  console.log('Saved settled services masthead and service-list screenshots.')
})().catch(error => { console.error(error); process.exitCode = 1 })

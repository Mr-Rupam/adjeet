const { createRequire } = require('node:module')
const fs = require('node:fs/promises')
const path = require('node:path')
const { chromium } = createRequire('C:/Users/KIIT0001/Downloads/AD_JEET/.superpowers/worktrees/era-build/adjeet-site/package.json')('playwright')
;(async () => {
  const browser = await chromium.launch({ headless: true })
  const page = await browser.newPage()
  const report = { failures: [], console: [], responses: [] }
  page.on('requestfailed', request => { if (request.url().includes('cloudflare')) report.failures.push({ url: request.url(), reason: request.failure() }) })
  page.on('response', response => { if (response.url().includes('cloudflare')) report.responses.push({ url: response.url(), status: response.status() }) })
  page.on('console', message => { if (message.type() === 'error') report.console.push(message.text()) })
  await page.route('**/api/lead', route => route.abort())
  await page.goto('http://localhost:4180/contact', { waitUntil: 'domcontentloaded' })
  await page.locator('#lead-name').fill('Local QA')
  await page.locator('button[type="submit"]').first().scrollIntoViewIfNeeded()
  await page.waitForTimeout(6000)
  report.dom = await page.evaluate(() => ({ widgetAPI: typeof window.turnstile, scripts: [...document.scripts].filter(script => script.src.includes('cloudflare')).map(script => script.src), frames: [...document.querySelectorAll('iframe')].map(frame => ({ src: frame.src, title: frame.title })), tokenInputs: [...document.querySelectorAll('input[name="cf-turnstile-response"]')].map(input => ({ hasValue: Boolean(input.value), length: input.value.length })), fallback: document.body.textContent.includes('CAPTCHA is temporarily unavailable') }))
  console.log(JSON.stringify(report, null, 2))
  await fs.writeFile(path.join(__dirname, 'captcha-inspection.json'), JSON.stringify(report, null, 2))
  await browser.close()
})().catch(error => { console.error(error); process.exitCode = 1 })

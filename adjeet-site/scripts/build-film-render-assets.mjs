// Makes the small files that keep the home film cheap to draw and never blank (run from adjeet-site/):
//   node scripts/build-film-render-assets.mjs
// 1. components/film/art-previews.ts: a 16 px wide WebP of every scene plate, base64, shown as the
//    plate's background until the plate itself arrives.
// 2. components/film/work-colors.ts: the average colour of each work photograph in the film, the
//    background of its frame until the photograph arrives.
// 3. public/client-logos/: brand wall logos larger than 400 x 160 px are downscaled in place to fit
//    that box (about twice the largest board face they are drawn on), same format, same name, same
//    shape. Never upscales; a second run changes nothing. content/home-film.ts keeps the original
//    width and height, which the wall uses for the shape and for its size caps.
// Read-only on the plates and the photographs; the logos are rewritten only when they are too large.
import { createRequire } from 'node:module'
import fs from 'node:fs/promises'
import path from 'node:path'

const root = process.cwd()
const sharp = createRequire(path.join(root, 'package.json'))('sharp')
const artDir = path.join(root, 'components', 'film', 'art')

// 1. Plate previews, keyed by the plate's file name without extension: the plates a scene opens on
//    (not the lit overlays, the truck layer or the finale, whose base is the hero's night picture).
const PLATES = [
  'brief-backdrop-day-tall', 'brief-backdrop-day-wide', 'brief-backdrop-night-tall', 'brief-backdrop-night-wide',
  'workshop-dusk-tall-dark', 'workshop-dusk-wide-dark',
  'road-empty-tall', 'road-golden-wide',
  'hills-dusk-tall-dark', 'hills-dusk-wide-dark',
  'junction-plain-tall-dark', 'junction-plain-wide-dark',
]
const previews = {}
for (const name of PLATES) {
  const buf = await sharp(path.join(artDir, `${name}.webp`)).resize({ width: 16 }).removeAlpha().webp({ quality: 60 }).toBuffer()
  previews[name] = `data:image/webp;base64,${buf.toString('base64')}`
}
const camel = s => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase())
await fs.writeFile(path.join(root, 'components', 'film', 'art-previews.ts'), [
  '// Generated by scripts/build-film-render-assets.mjs from components/film/art/*.webp. Do not edit.',
  '/** A 16 px wide WebP of each scene plate (base64): the plate\'s background until the plate arrives. */',
  'export const PREVIEW = {',
  ...Object.entries(previews).map(([name, url]) => `  ${camel(name)}: '${url}',`),
  '} as const',
  '',
].join('\n'))

// 2. Work photo average colours.
const film = await fs.readFile(path.join(root, 'content', 'home-film.ts'), 'utf8')
const gallery = await fs.readFile(path.join(root, 'content', 'gallery.ts'), 'utf8')
const picks = [...film.slice(film.indexOf('WORK_PICKS')).matchAll(/\{ id: '([^']+)'/g)].map(m => m[1]).slice(0, 40)
const srcOf = {}
for (const m of gallery.matchAll(/id: '([^']+)',\s*\n\s*src: '([^']+)'/g)) srcOf[m[1]] = m[2]
const colours = {}
for (const id of picks) {
  if (!srcOf[id]) continue
  const { channels } = await sharp(path.join(root, 'public', srcOf[id])).stats()
  colours[id] = '#' + channels.slice(0, 3).map(c => Math.round(c.mean).toString(16).padStart(2, '0')).join('')
}
await fs.writeFile(path.join(root, 'components', 'film', 'work-colors.ts'), [
  '// Generated by scripts/build-film-render-assets.mjs from the photographs in public/. Do not edit.',
  '/** Each film work photograph\'s average colour: its frame\'s background until the photograph arrives. */',
  'export const WORK_COLOR: Record<string, string> = {',
  ...Object.entries(colours).map(([id, c]) => `  '${id}': '${c}',`),
  '}',
  '',
].join('\n'))

// 3. Logos: the files the brand wall shows (content/home-film.ts). Each is written in whichever of a
//    lossless and a high-quality encoding of its format is smaller.
const BOX = { width: 400, height: 160 }
const logoDir = path.join(root, 'public', 'client-logos')
const wallLogos = [...new Set([...film.matchAll(/'\/client-logos\/([^']+)'/g)].map(m => m[1]))]
for (const file of wallLogos) {
  const p = path.join(logoDir, file)
  const input = await fs.readFile(p)
  const meta = await sharp(input).metadata()
  if (meta.width <= BOX.width && meta.height <= BOX.height) continue
  const resized = () => sharp(input).resize({ ...BOX, fit: 'inside', withoutEnlargement: true })
  const tries = file.endsWith('.png')
    ? [resized().png({ compressionLevel: 9, effort: 10 }), resized().png({ palette: true, quality: 95, effort: 10, compressionLevel: 9 })]
    : [resized().webp({ lossless: true, effort: 6 }), resized().webp({ quality: 92, alphaQuality: 100, effort: 6 })]
  const outs = await Promise.all(tries.map(t => t.toBuffer()))
  const out = outs.reduce((a, b) => (b.length < a.length ? b : a))
  if (out.length >= input.length) { console.log(`logo ${file}: ${meta.width}x${meta.height} kept, a smaller copy would be more bytes`); continue }
  const after = await sharp(out).metadata()
  await fs.writeFile(p, out)
  console.log(`logo ${file}: ${meta.width}x${meta.height} ${input.length} B -> ${after.width}x${after.height} ${out.length} B`)
}
console.log(`previews ${Object.keys(previews).length}, colours ${Object.keys(colours).length}`)
